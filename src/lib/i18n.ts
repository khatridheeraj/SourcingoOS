const STEP_HI: [RegExp, string][] = [
  [/fabric\s*sourc|fabric\s*book|fabric in/i, "कपड़ा खरीद"], [/lab\s*dip/i, "लैब डिप"], [/pp\s*sample|pre-?production/i, "पीपी सैंपल"],
  [/fit\s*sample/i, "फ़िट सैंपल"], [/cutting/i, "कटिंग"], [/sewing|stitch/i, "सिलाई"], [/embroider/i, "कढ़ाई"], [/print/i, "छपाई"],
  [/dye|dyeing/i, "रंगाई"], [/wash/i, "धुलाई"], [/finish/i, "फ़िनिशिंग"], [/trim|accessor/i, "ट्रिम्स"], [/qc|inspect|quality/i, "क्वालिटी जांच"],
  [/pack/i, "पैकिंग"], [/dispatch|ship/i, "डिस्पैच के लिए तैयार"], [/weav/i, "बुनाई"], [/greige/i, "ग्रे कपड़ा"],
];
export function stepName(name: string, lang: Lang) {
  if (lang !== "hi") return name;
  const hit = STEP_HI.find(([re]) => re.test(name));
  return hit ? `${hit[1]} · ${name}` : name;
}

